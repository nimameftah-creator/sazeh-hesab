async function main() {
  const cats = await db.select().from(categories);
  const catId = (stage: string) => cats.find((c) => c.stage === stage)?.id ?? null;

  const existing = await db.select({ id: materials.id, name: materials.name }).from(materials);
  const have = new Set(existing.map((m) => m.name));

  const rows = CATALOG.filter(([name]) => !have.has(name)).map(([name, unit, keywords, stage]) => ({
    name,
    unit,
    keywords,
    categoryId: catId(stage),
  }));

  if (rows.length === 0) {
    console.log("کاتالوگ کالاها قبلاً وجود دارد — چیزی اضافه نشد.");
  } else {
    await db.insert(materials).values(rows);
    console.log(`✓ ${rows.length} کالا به کاتالوگ اضافه شد.`);
  }

  const count = await db.execute(sql`select count(*)::int as n from materials`);
  console.log("مجموع کالاها:", (count as unknown as { rows: { n: number }[] })?.rows?.[0]?.n ?? "?");
}

main()
  .then(() => process.exit(0))
  .catch((e) => {
    console.error(e);
    process.exit(1);
  });
